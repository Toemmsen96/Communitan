// Storage + static-data helpers.

const STORE_SYSTEM_USER = "00000000-0000-0000-0000-000000000000";

function storeGet(nk: nkruntime.Nakama, collection: string, key: string, userId: string): any {
    const r = nk.storageRead([{ collection: collection, key: key, userId: userId }]);
    return r.length > 0 ? r[0].value : null;
}

// version "*" = create only if absent (throws if present); "" = unconditional.
function storePut(nk: nkruntime.Nakama, collection: string, key: string, userId: string, value: any, version = "") {
    const req: nkruntime.StorageWriteRequest = { collection: collection, key: key, userId: userId, value: value, permissionRead: 1, permissionWrite: 0 };
    if (version) req.version = version;
    nk.storageWrite([req]);
}

// Read-modify-write with defaults; `init` builds the default doc when absent. Returns the stored doc.
function storeGetOrInit(nk: nkruntime.Nakama, collection: string, key: string, userId: string, init: () => any): any {
    const v = storeGet(nk, collection, key, userId);
    if (v) return v;
    const d = init();
    storePut(nk, collection, key, userId, d);
    return d;
}

// Static data from CATAN_DATA_DIR (docker: /nakama/data/catan); fileRead is relative to the runtime path (/nakama/data/modules).
const STORE_DATA_CACHE: { [name: string]: any } = {};

function dataLoad(ctx: nkruntime.Context, nk: nkruntime.Nakama, name: string): any {
    const d = dataLoadOpt(ctx, nk, name);
    if (d === null) throw new Error("data file not found: " + name);
    return d;
}

// Optional data file (e.g. almanac.json, generated by the host): null when absent. Absence is cached too.
function dataLoadOpt(ctx: nkruntime.Context, nk: nkruntime.Nakama, name: string): any {
    if (STORE_DATA_CACHE[name] !== undefined) return STORE_DATA_CACHE[name];
    const dir = (ctx.env && ctx.env["CATAN_DATA_DIR"]) || "/nakama/data/catan";
    let text: string | null = null;
    for (const p of [dir + "/" + name, "../catan/" + name]) {
        try { text = nk.fileRead(p); break; } catch (e) { /* try next */ }
    }
    STORE_DATA_CACHE[name] = text === null ? null : JSON.parse(text);
    return STORE_DATA_CACHE[name];
}
