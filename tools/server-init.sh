#!/usr/bin/env bash
# Generate random secrets into <server dir>/.env. Idempotent: never overwrites an existing .env.
# Usage: tools/server-init.sh [server-dir]   (default: ../server next to tools/, or ./ in the server release zip)
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
dir="${1:-}"
if [[ -z "$dir" ]]; then
  if [[ -f "$here/../server/compose.yml" ]]; then dir="$here/../server"; else dir="$here/.."; fi
fi
[[ -f "$dir/compose.yml" ]] || { echo "compose.yml not found in $dir" >&2; exit 1; }
env="$dir/.env"
if [[ -e "$env" ]]; then echo "$env already exists, not touching it."; exit 0; fi
rnd() { head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n'; }
umask 077
{
  echo "# Generated by server-init.sh on $(date -u +%F). Keep private, never commit."
  echo "POSTGRES_PASSWORD=$(rnd)"
  echo "SESSION_ENCRYPTION_KEY=$(rnd)"
  echo "SESSION_REFRESH_ENCRYPTION_KEY=$(rnd)"
  echo "CONSOLE_USERNAME=admin"
  echo "CONSOLE_PASSWORD=$(rnd | head -c 24)"
  echo "CONSOLE_SIGNING_KEY=$(rnd)"
  echo "# Public by design: players enter this in the mod (Advanced). Change per server and tell your players."
  echo "NAKAMA_SERVER_KEY=defaultkey"
  echo "LOG_LEVEL=INFO"
  echo "# Public status key (not a secret): the mod reads player counts with it before login; nothing else accepts it."
  echo "NAKAMA_HTTP_KEY=catan-public-status"
  echo "# New email accounts: ingame = 6-digit activation code shown in-game (no mail is sent), off = verified immediately"
  echo "CATAN_EMAIL_VERIFICATION=ingame"
  echo "# Randomness: off = the creator's client picks seeds (vanilla), seeds = the server picks them, full = server dice + draws, mod required (docs/design/server-rng.md)"
  echo "CATAN_SERVER_RNG=off"
  echo "# Paid content: free = what a free official account has, owned = + each player's own official purchases (mirrored by the mod). See README liability section"
  echo "CATAN_ENTITLEMENTS=free"
  echo "# HTTPS (docker compose --profile https up -d): uncomment, see docs/HOSTING.md"
  echo "# DOMAIN=catan.example.org"
  echo "# NAKAMA_BIND=127.0.0.1"
} > "$env"
echo "Wrote $env (mode 600). Console login: admin / $(grep ^CONSOLE_PASSWORD "$env" | cut -d= -f2)"
echo "NOTE: if a database volume already exists, POSTGRES_PASSWORD must match the old one (edit .env)."
